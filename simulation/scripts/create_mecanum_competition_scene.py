"""Compose and run the 4-mecanum-wheel competition scene in Isaac Sim.

Builds on create_mobile_manipulator_scene.py but replaces the kinematic
diff-drive robot with the physics-articulated mecanum robot generated by
generate_mecanum_robot_urdf.py (Kaya-style passive sphere rollers at 45 deg).

The runtime bridge mirrors the REAL mecanum stack's ROS contract
(src/robot_hardware/robot_hardware/mecanum_bridge_node.py):
  subscribe /cmd_vel (+ /cmd_vel_direct > /cmd_vel > /cmd_vel_smoothed >
            /cmd_vel_nav priority mux, 0.5 s timeout, same as the old sim),
            /base/move_relative (String JSON {dx,dy,dyaw}), /safety/e_stop,
            /gripper/command (String OPEN/CLOSE), /mk1/gripper_joint_command
  publish  /odom/wheel (+ /chassis/odom alias), /joint_states, /motor/state
           (String JSON, drive_type=mecanum), /base/move_result, /clock,
           /laser_scan (re-stamped from the Isaac lidar raw topic), TF
           odom->base_link, /sim/ground_truth_pose (String JSON).

Wheel command mixing uses the repo's own MecanumKinematics so the sim
exercises the exact IK/FK the real robot runs.

Drive modes:
  --drive-mode physics   (default) velocity drives on the 4 wheel joints;
                         the mecanum behaviour emerges from roller contact.
  --drive-mode kinematic fallback: integrates the commanded body twist and
                         teleports the (kinematic) root, like the old
                         diff-drive sim bridge but holonomic.
"""

