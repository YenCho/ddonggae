    def _gripper_string_callback(self, msg):
        command = str(msg.data).strip().upper()
        if command.startswith("OPEN"):
            self.gripper_travel = GRIPPER_OPEN_TRAVEL_M
            self._release_object()
        elif command.startswith("CLOSE"):
            self.gripper_travel = 0.0
            self._try_grab_object()

    # --- cheat-grip: attach the nearest competition object on CLOSE ------
    # Physical finger grasping of the printed objects is out of scope for the
    # strategy rehearsal; CLOSE latches the nearest object within reach to the
    # gripper (kinematic follow), OPEN releases it in place.
    # Grip zone modeled on the REAL parallel gripper (not a radius): fingers
    # span x in [0.095, 0.245] ahead of base center (10cm finger length from
    # the 0.145 gripper point +-), tips open to +-0.1025 so an 8cm object
    # must sit within +-0.06 laterally to be enclosed.
    GRIP_ZONE_FWD_MIN_M = 0.095
    GRIP_ZONE_FWD_MAX_M = 0.245
    GRIP_ZONE_LAT_M = 0.06
    GRIP_FORWARD_OFFSET_M = 0.145
    GRIP_CARRY_HEIGHT_M = 0.12

    def _gripper_world_point(self) -> tuple[float, float]:
        gt = self._ground_truth_pose()
        if gt is None:
            return self.x, self.y
        x, y, yaw = gt
        return (
            x + math.cos(yaw) * self.GRIP_FORWARD_OFFSET_M,
            y + math.sin(yaw) * self.GRIP_FORWARD_OFFSET_M,
        )

    def _object_center(self, prim) -> tuple[float, float]:
        """World XY of the object's geometry center.

        The pivotFix bake puts the GEOMETRY on the grid point but moves the
        prim frame origin the other way (banana: 0.5m!), so the offset from
        origin to bbox center is measured ONCE per prim and cached."""
        import omni.usd
        from pxr import Usd, UsdGeom

        if not hasattr(self, "_center_offsets"):
            self._center_offsets = {}
        path = str(prim.GetPath())
        matrix = omni.usd.get_world_transform_matrix(prim)
        t = matrix.ExtractTranslation()
        if path not in self._center_offsets:
            cache = UsdGeom.BBoxCache(Usd.TimeCode.Default(), ["default", "render"])
            box = cache.ComputeWorldBound(prim).ComputeAlignedRange()
            center = (box.GetMax() + box.GetMin()) * 0.5
            self._center_offsets[path] = (float(center[0]) - float(t[0]), float(center[1]) - float(t[1]))
        off = self._center_offsets[path]
        return float(t[0]) + off[0], float(t[1]) + off[1]

    def _try_grab_object(self):
        from pxr import Usd, UsdPhysics

        if getattr(self, "held_object", None):
            return
        gt = self._ground_truth_pose()
        if gt is None:
            return
        bx, by, byaw = gt
        gx, gy = self._gripper_world_point()
        cos_y, sin_y = math.cos(byaw), math.sin(byaw)
        best = None
        root = self.stage.GetPrimAtPath("/World/CompetitionObjects")
        if not root.IsValid():
            return

        for prim in root.GetChildren():
            cx, cy = self._object_center(prim)
            # Object position in the robot frame: rectangular grip zone.
            fwd = (cx - bx) * cos_y + (cy - by) * sin_y
            lat = -(cx - bx) * sin_y + (cy - by) * cos_y
            if (self.GRIP_ZONE_FWD_MIN_M <= fwd <= self.GRIP_ZONE_FWD_MAX_M
                    and abs(lat) <= self.GRIP_ZONE_LAT_M):
                dist = math.hypot(cx - gx, cy - gy)
                if best is None or dist < best[0]:
                    best = (dist, prim)
        if best is None:
            # Diagnose misses: where was the nearest object relative to the
            # gripper when CLOSE found nothing in reach?
            nearest = None
            for prim in root.GetChildren():
                cx, cy = self._object_center(prim)
                d = math.hypot(cx - gx, cy - gy)
                if nearest is None or d < nearest[0]:
                    nearest = (d, prim.GetName(), round(cx - gx, 3), round(cy - gy, 3))
            if nearest:
                self.node.get_logger().warn(
                    f"grip MISS: nearest {nearest[1]} at {nearest[0]:.3f}m "
                    f"(dx={nearest[2]}, dy={nearest[3]} world)"
                )
            return
        _, prim = best
        for target in [prim, *Usd.PrimRange(prim)]:
            if target.HasAPI(UsdPhysics.RigidBodyAPI):
                target.GetAttribute("physics:kinematicEnabled").Set(True)
            # Disable collisions while carried: the kinematic body follows the
            # gripper and would otherwise fight the robot's own colliders.
            if target.HasAPI(UsdPhysics.CollisionAPI):
                UsdPhysics.CollisionAPI(target).CreateCollisionEnabledAttr(False)
        self.held_object = str(prim.GetPath())
        self.node.get_logger().info(f"cheat-grip: grabbed {self.held_object}")

    RELEASE_FORWARD_M = 0.035   # clear of the gripper backstop wall
    RELEASE_REST_Z_M = 0.093    # just above the 8 cm object's rest height

    def _release_object(self):
        from pxr import Gf, Usd, UsdGeom, UsdPhysics

        held = getattr(self, "held_object", None)
        if not held:
            return
        prim = self.stage.GetPrimAtPath(held)
        if prim.IsValid():
            # Re-enabling collision while the carried object overlaps the
            # backstop/fingers makes PhysX resolve a deep penetration with a
            # violent impulse (objects were shot through the floor). Teleport
            # to a clear rest pose FIRST, then restore physics.
            gt = self._ground_truth_pose()
            if gt is not None:
                x, y, yaw = gt
                release_x = x + math.cos(yaw) * (self.GRIP_FORWARD_OFFSET_M + self.RELEASE_FORWARD_M)
                release_y = y + math.sin(yaw) * (self.GRIP_FORWARD_OFFSET_M + self.RELEASE_FORWARD_M)
                # Stacking: if another object already occupies the release
                # spot, rest on top of it instead of inside it.
                release_z = self.RELEASE_REST_Z_M
                root = self.stage.GetPrimAtPath("/World/CompetitionObjects")
                if root.IsValid():
                    for other in root.GetChildren():
                        if str(other.GetPath()) == held:
                            continue
                        ox_, oy_ = self._object_center(other)
                        if math.hypot(ox_ - release_x, oy_ - release_y) < 0.07:
                            release_z = self.RELEASE_REST_Z_M + 0.085
                            break
                xform = UsdGeom.Xformable(prim)
                for op in xform.GetOrderedXformOps():
                    if op.GetOpName() == "xformOp:translate":
                        # translate value == geometry center (pivotFix bake).
                        op.Set(Gf.Vec3d(release_x, release_y, release_z))
                        break
            for target in [prim, *Usd.PrimRange(prim)]:
                if target.HasAPI(UsdPhysics.RigidBodyAPI):
                    target.GetAttribute("physics:kinematicEnabled").Set(False)
                if target.HasAPI(UsdPhysics.CollisionAPI):
                    UsdPhysics.CollisionAPI(target).CreateCollisionEnabledAttr(True)
        self.node.get_logger().info(f"cheat-grip: released {held}")
        self.held_object = None

    def _update_held_object(self):
        from pxr import Gf, UsdGeom

        held = getattr(self, "held_object", None)
        if not held:
            return
        prim = self.stage.GetPrimAtPath(held)
        if not prim.IsValid():
            self.held_object = None
            return
        gx, gy = self._gripper_world_point()
        xform = UsdGeom.Xformable(prim)
        translate_op = None
        for op in xform.GetOrderedXformOps():
            if op.GetOpName() == "xformOp:translate":
                translate_op = op
                break
        if translate_op is None:
            translate_op = xform.AddTranslateOp(precision=UsdGeom.XformOp.PrecisionDouble)
        # Under the pivotFix bake the translate op value IS the geometry
        # center's world position - write the target directly. (The cached
        # offset is only for READS: matrix origin -> center.)
        translate_op.Set(Gf.Vec3d(gx, gy, self.GRIP_CARRY_HEIGHT_M))

    def _ground_truth_pose(self):
        if self.articulation is None:
            # Kinematic drive: the integrated bridge pose IS ground truth.
            return self.x, self.y, self.yaw
        positions, orientations = self.articulation.get_world_poses()
        p = self._to_list(positions)
        q = self._to_list(orientations)[:4]
        yaw = math.atan2(2.0 * (q[0] * q[3] + q[1] * q[2]), 1.0 - 2.0 * (q[2] ** 2 + q[3] ** 2))
        return p[0], p[1], yaw - math.radians(USD_VISUAL_YAW_OFFSET_DEG)

