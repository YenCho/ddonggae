def load_urdf_geometry(urdf: Path) -> None:
    """Adopt wheel geometry from the generated URDF's mecanum_* attributes."""
    import xml.etree.ElementTree as ET

    global WHEEL_RADIUS_M, HALF_LENGTH_M, HALF_WIDTH_M
    root = ET.parse(str(urdf)).getroot()
    radius = root.get("mecanum_wheel_radius_m")
    half_length = root.get("mecanum_half_length_m")
    half_width = root.get("mecanum_half_width_m")
    if radius:
        WHEEL_RADIUS_M = float(radius)
    if half_length:
        HALF_LENGTH_M = float(half_length)
    if half_width:
        HALF_WIDTH_M = float(half_width)


def usd_asset_path(path: Path, relative_to: Path | None = None) -> str:
    if relative_to is not None:
        path = Path(os.path.relpath(path, start=relative_to))
    return str(path).replace("\\", "/")


