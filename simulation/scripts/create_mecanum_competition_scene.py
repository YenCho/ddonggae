    # --- callbacks -------------------------------------------------------
    def _cmd_callback(self, msg, source: str):
        now = time.monotonic()
        vx = float(msg.linear.x)
        vy = float(msg.linear.y)
        wz = float(msg.angular.z)
        if not all(math.isfinite(v) for v in (vx, vy, wz)):
            vx = vy = wz = 0.0
        vx = max(min(vx, MAX_LINEAR_X_MPS), -MAX_LINEAR_X_MPS)
        vy = max(min(vy, MAX_LINEAR_Y_MPS), -MAX_LINEAR_Y_MPS)
        wz = max(min(wz, MAX_ANGULAR_RPS), -MAX_ANGULAR_RPS)
        self.cmd_by_source[source] = (vx, vy, wz, now)
        # A nonzero manual twist preempts an active relative move (real
        # bridge behaviour).
        if self.move_target is not None and (abs(vx) > 1e-4 or abs(vy) > 1e-4 or abs(wz) > 1e-4):
            self._finish_move(ok=False, reason="preempted_by_cmd_vel")

    def _select_cmd(self, now: float) -> tuple[float, float, float]:
        for source in CMD_SOURCE_PRIORITY:
            command = self.cmd_by_source.get(source)
            if command is None:
                continue
            vx, vy, wz, stamp = command
            if now - stamp <= CMD_SOURCE_TIMEOUT_SEC:
                return vx, vy, wz
        return 0.0, 0.0, 0.0

    def _move_relative_callback(self, msg):
        try:
            payload = json.loads(msg.data)
            dx = float(payload.get("dx", 0.0))
            dy = float(payload.get("dy", 0.0))
            dyaw = float(payload.get("dyaw", 0.0))
        except (ValueError, TypeError) as exc:
            self._publish_move_result(ok=False, reason=f"bad_json:{exc}")
            return
        if self.move_target is not None:
            self._publish_move_result(ok=False, reason="busy")
            return
        cos_yaw = math.cos(self.yaw)
        sin_yaw = math.sin(self.yaw)
        target_x = self.x + dx * cos_yaw - dy * sin_yaw
        target_y = self.y + dx * sin_yaw + dy * cos_yaw
        target_yaw = normalize_angle(self.yaw + dyaw)
        self.move_target = (target_x, target_y, target_yaw, time.monotonic())
        self._move_progress = None  # restart the stall guard for this move
        try:
            self.move_speed_cap = float(payload.get("max_v")) if payload.get("max_v") else None
        except (TypeError, ValueError):
            self.move_speed_cap = None

